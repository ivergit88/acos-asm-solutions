; Читаем число 0..99 и печатаем его удвоенное значение: 21 -> Result: 42.
; На входе по условию корректные цифры и перевод строки.
bits 64
global _start

section .rodata            ; постоянные данные, которые не будем менять
prefix: db "Result: "      ; 8 символов, включая пробел после двоеточия

section .bss               ; память под буферы; при запуске она заполнена нулями
inbuf:  resb 32            ; сюда read положит введённые символы
numbuf: resb 5             ; здесь подготовим текст результата и перевод строки

section .text
_start:
    ; Сначала задаём аргументы read. Само чтение начнётся только на syscall.
    xor eax, eax           ; обнулить EAX: номер read равен 0
    xor edi, edi           ; 0 — стандартный ввод
    lea rsi, [rel inbuf]   ; RSI получает адрес буфера, а не его содержимое
    mov edx, 32            ; можно прочитать не больше 32 байт
    syscall                ; для ввода 21 буфер получит байты 32 31 0A

    ; Собираем число по цифрам: накопленное * 10 + следующая цифра.
    lea rsi, [rel inbuf]   ; вернуться к началу введённой строки
    xor eax, eax           ; пока разобранное число равно нулю
next:
    movzx ecx, byte [rsi]  ; прочитать один символ из памяти и расширить его нулями
    cmp ecx, 10            ; 10 (0A) — перевод строки LF
    je parsed              ; дошли до конца строки — разбор закончен
    cmp ecx, 13            ; также останавливаемся на CR
    je parsed
    cmp ecx, '0'           ; символ должен быть в диапазоне '0'..'9'
    jb parsed
    cmp ecx, '9'
    ja parsed
    sub ecx, '0'           ; из кода символа получить цифру: '2' - '0' = 2
    imul eax, eax, 10      ; освободить следующий десятичный разряд
    add eax, ecx           ; прибавить цифру: сначала 2, потом 2*10+1 = 21
    inc rsi                ; сдвинуть адрес на следующий символ
    jmp next
parsed:
    add eax, eax           ; удвоить само число: 21 + 21 = 42

    ; Остатки от деления дают цифры с конца, поэтому пишем справа налево.
    lea rdi, [rel numbuf + 4]
    mov ebx, 10            ; делитель для получения десятичных цифр
    xor ecx, ecx           ; счётчик записанных цифр
digits:
    xor edx, edx           ; перед КАЖДЫМ делением очистить старшую половину EDX:EAX
    div ebx                ; EAX — частное, EDX — остаток: для 42 это 4 и 2
    add dl, '0'            ; превратить остаток в символ цифры
    dec rdi                ; выделить место на один символ левее
    mov byte [rdi], dl     ; записать цифру в память
    inc ecx                ; посчитать записанную цифру
    test eax, eax          ; осталось ли что-то в частном?
    jnz digits             ; если осталось, получить следующую цифру
    ; Цикл проходит хотя бы раз: число 0 тоже превращается в символ '0'.
    mov byte [rdi + rcx], 10 ; после цифр поставить LF
    mov r8, rdi            ; сохранить адрес первой цифры
    lea r9, [rcx + 1]      ; сохранить длину: цифры плюс LF

    ; syscall меняет RCX и R11, поэтому длину заранее сохранили в R9.
    mov eax, 1             ; номер write
    mov edi, 1             ; 1 — стандартный вывод
    lea rsi, [rel prefix]  ; адрес строки Result:
    mov edx, 8             ; вывести 8 байт префикса
    syscall
    mov eax, 1             ; второй write печатает само число
    mov edi, 1
    mov rsi, r8             ; адрес первой цифры
    mov rdx, r9             ; количество цифр вместе с LF
    syscall
    mov eax, 60            ; номер exit
    xor edi, edi           ; код 0 — успешное завершение, ответ уже напечатан
    syscall

section .note.GNU-stack noalloc noexec nowrite progbits
