; Ищем минимум трёх целых чисел. Для 7, 3 и 2 ответ — 2.
; A, B и C задаются при сборке, вводить их с клавиатуры здесь не нужно.
%ifndef A
    %define A 7
%endif
%ifndef B
    %define B 3
%endif
%ifndef C
    %define C 2
%endif
bits 64                    ; программа работает в режиме x86-64
global _start              ; отсюда начнётся выполнение
section .text              ; дальше идут инструкции
_start:
    ; В MOV слева — куда записать, справа — откуда взять значение.
    mov eax, A             ; считаем первое число текущим минимумом
    mov ebx, B
    mov ecx, C

    cmp eax, ebx           ; сравнить текущий минимум со вторым числом
    jle check_c            ; если он уже <= B, оставляем его и проверяем C
    mov eax, ebx           ; иначе второе число меньше — выбираем его
check_c:
    cmp eax, ecx           ; теперь сравнить выбранный минимум с третьим числом
    jle done               ; если он <= C, ответ уже найден
    mov eax, ecx           ; иначе минимум — третье число
done:
    mov edi, eax           ; сохранить ответ до того, как перезапишем EAX
    mov eax, 60            ; 60 — номер системного вызова exit в Linux x86-64
    syscall                ; завершиться; ответ виден через echo $?
; Служебная отметка: выполнять код на стеке не нужно.
section .note.GNU-stack noalloc noexec nowrite progbits
